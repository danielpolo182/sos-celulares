export interface ModeloDispositivo {
  marca: string
  modelo: string
}

function gerarSlug(modelo: string): string {
  return modelo
    .toLowerCase()
    .replace(/\s+/g, '-')
    .replace(/[^a-z0-9-]/g, '')
}

export function gerarModelos(): (ModeloDispositivo & { slug: string })[] {
  return MODELOS_RAW.map(m => ({ ...m, slug: gerarSlug(m.modelo) }))
}

export function gerarModelosPorMarca(marca: string): (ModeloDispositivo & { slug: string })[] {
  return gerarModelos().filter(m => m.marca.toLowerCase() === marca.toLowerCase())
}

